// `verify` (spec 5.5, GEN-06 to GEN-08): runs each emitted test file against another copy of the module, in its own
// `--permission` child with the recorder's network guard, parses the TAP stream and writes verify.json.
// `--permission` cannot be combined with `--test` (the runner spawns a process per file), so every file is run
// directly; `--test-force-exit` ends a passing file whose target leaves a timer running; a file watchdog SIGKILLs a
// file that never finishes (a synchronous loop is out of reach of node's own test timeout).
// The child's stdout is a temporary file, not a pipe: node writes to a file synchronously, so the whole TAP stream is on
// disk when `--test-force-exit` calls `process.exit`, however late this process gets to read it. Through a pipe, what
// the child had not yet handed to the kernel was dropped at that exit whenever a loaded machine kept the parent from
// reading in time (delta 106). A file that reports fewer results than it has tests never reads as a pass.
import { spawn } from "node:child_process";
import { closeSync, existsSync, fstatSync, mkdirSync, mkdtempSync, openSync, readFileSync, readSync, readdirSync, realpathSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { pathToFileURL } from "node:url";
import { writeJsonText } from "../contracts/stable-json.ts";
import { LaError } from "../infra/errors.ts";
import type { Logger } from "../infra/logger.ts";
import { HARNESS_DIR, relativeToProject } from "../infra/paths.ts";
import { redactSecrets } from "../infra/redact.ts";
import { TEST_FILE_SUFFIX } from "./generate.ts";
import { parseTap } from "./tap.ts";

export type VerifyFailure = { name: string; caseId: string | null; message: string };
export type VerifyFile = { file: string; tests: number; passed: number; failed: number; timedOut: boolean; failures: VerifyFailure[] };
export type VerifyReport = { target: string; files: VerifyFile[] };

const MODULE_EXTENSIONS = [".js", ".cjs", ".mjs", ".ts", ".mts"] as const;
const MODULE_NAME_LINE = /^const MODULE_NAME = "(.+)";$/m;
const STDOUT_CAP = 16 * 1024 * 1024;
const STDOUT_POLL_MS = 100;
const STDERR_CAP = 64 * 1024;
const MAX_MESSAGE = 2000;

type Planned = { name: string; path: string; moduleName: string; plannedTests: number };
type ChildRun = { code: number | null; stdout: string; stderr: string; timedOut: boolean; capped: boolean; durationMs: number };

function plan(testsDir: string, againstReal: string): Planned[] {
  if (!existsSync(testsDir)) throw new LaError("USAGE", `no tests directory at ${testsDir}; pass --tests-dir or run \`run\` first`);
  const names = readdirSync(testsDir).filter((n) => n.endsWith(TEST_FILE_SUFFIX)).sort();
  if (names.length === 0) throw new LaError("USAGE", `no *${TEST_FILE_SUFFIX} file in ${testsDir}; run \`run\` first`);
  const planned: Planned[] = [];
  for (const name of names) {
    const path = join(testsDir, name);
    const text = readFileSync(path, "utf8");
    const m = MODULE_NAME_LINE.exec(text);
    if (!m) throw new LaError("USAGE", `${name} is not a file generated by legacy-archaeologist (no MODULE_NAME line)`);
    const moduleName = JSON.parse(`"${m[1] as string}"`) as string;
    // Checked before any spawn, so a missing module is exit 2 and never mistaken for a behavior failure (delta 9).
    if (!MODULE_EXTENSIONS.some((ext) => existsSync(join(againstReal, moduleName + ext)))) {
      throw new LaError("MODULE_NOT_FOUND_IN_AGAINST", `${relativeToProject(againstReal)}/${moduleName} (tried ${MODULE_EXTENSIONS.join(", ")})`);
    }
    planned.push({ name, path, moduleName, plannedTests: (text.match(/^test\(/gm) ?? []).length });
  }
  return planned;
}

// The first STDOUT_CAP bytes of the child's stdout file.
function readCapped(fd: number): string {
  const bytes = Buffer.alloc(Math.min(fstatSync(fd).size, STDOUT_CAP));
  let offset = 0;
  while (offset < bytes.length) {
    const n = readSync(fd, bytes, offset, bytes.length - offset, offset);
    if (n === 0) break;
    offset += n;
  }
  return bytes.subarray(0, offset).toString("utf8");
}

function runFile(file: string, testsReal: string, againstReal: string, fileTimeoutMs: number): Promise<ChildRun> {
  const args = [
    "--permission",
    `--allow-fs-read=${testsReal}`,
    `--allow-fs-read=${againstReal}`,
    `--allow-fs-read=${HARNESS_DIR}`,
    "--import",
    pathToFileURL(join(HARNESS_DIR, "net-guard-entry.ts")).href,
    "--test-force-exit",
    "--test-reporter=tap",
    file,
  ];
  const env = { TZ: "UTC", LANG: "C", LC_ALL: "C", NODE_OPTIONS: "", PATH: "", LA_TARGET_DIR: againstReal };
  const started = performance.now();
  // Outside every directory the child may read; the child only inherits the open descriptor as its fd 1.
  const scratch = mkdtempSync(join(tmpdir(), "la-verify-"));
  const fd = openSync(join(scratch, "stdout.tap"), "w+");
  let open = true;
  const cleanup = (): void => {
    if (!open) return;
    open = false;
    closeSync(fd);
    rmSync(scratch, { recursive: true, force: true });
  };
  return new Promise((resolve, reject) => {
    let child: ReturnType<typeof spawn>;
    try {
      child = spawn(process.execPath, args, { cwd: testsReal, env, stdio: ["ignore", fd, "pipe"] });
    } catch (err) {
      cleanup();
      throw err;
    }
    let stderr = "";
    let timedOut = false;
    let capped = false;
    child.stderr?.setEncoding("utf8").on("data", (chunk: string) => {
      if (stderr.length < STDERR_CAP) stderr += chunk;
    });
    const timer = setTimeout(() => {
      timedOut = true;
      child.kill("SIGKILL");
    }, fileTimeoutMs);
    // The file grows on disk, not in memory: a file whose stdout passes the cap is killed.
    const poll = setInterval(() => {
      if (open && !capped && fstatSync(fd).size > STDOUT_CAP) {
        capped = true;
        child.kill("SIGKILL");
      }
    }, STDOUT_POLL_MS);
    child.on("error", (err) => {
      clearTimeout(timer);
      clearInterval(poll);
      cleanup();
      reject(new LaError("CHILD_SPAWN", `could not start the test child: ${err.message}`));
    });
    child.on("close", (code) => {
      clearTimeout(timer);
      clearInterval(poll);
      if (!open) return;
      const stdout = readCapped(fd);
      cleanup();
      resolve({ code, stdout, stderr, timedOut, capped, durationMs: Math.round(performance.now() - started) });
    });
  });
}

function caseIdOf(name: string): string | null {
  const m = /^\[([^\]]+)\]/.exec(name);
  return m ? (m[1] as string) : null;
}

function cleanMessage(message: string): string {
  return redactSecrets(message).replace(/[\r\n]+/g, " ").slice(0, MAX_MESSAGE);
}

function toVerifyFile(p: Planned, run: ChildRun): VerifyFile {
  const tap = parseTap(run.stdout);
  const passed = tap.tests.filter((t) => t.ok).length;
  const failures: VerifyFailure[] = tap.tests.filter((t) => !t.ok).map((t) => ({ name: t.name, caseId: caseIdOf(t.name), message: cleanMessage(t.message ?? "failed without a message") }));
  const file = relativeToProject(p.path);
  if (run.timedOut) {
    const tests = Math.max(p.plannedTests, tap.tests.length);
    return { file, tests, passed, failed: tests - passed, timedOut: true, failures };
  }
  if (run.capped) {
    const tests = Math.max(p.plannedTests, tap.tests.length, 1);
    return { file, tests, passed, failed: tests - passed, timedOut: false, failures: [...failures, { name: file, caseId: null, message: `killed: stdout passed ${STDOUT_CAP / (1024 * 1024)} MiB` }] };
  }
  if (run.code !== 0 && failures.length === 0) {
    // The file failed outside any test (a syntax error, a crash at load): every planned test counts as failed.
    const tests = Math.max(p.plannedTests, tap.tests.length, 1);
    const firstLine = run.stderr.split("\n").map((l) => l.trim()).find((l) => l !== "") ?? `exited with code ${String(run.code)}`;
    return { file, tests, passed, failed: tests - passed, timedOut: false, failures: [{ name: file, caseId: null, message: cleanMessage(firstLine) }] };
  }
  if (tap.tests.length < p.plannedTests) {
    // The file exited before reporting every test (the target called process.exit, or output was lost): each test
    // without a result counts as failed, so a short TAP stream never reads as a pass.
    const tests = p.plannedTests;
    return { file, tests, passed, failed: tests - passed, timedOut: false, failures: [...failures, { name: file, caseId: null, message: `the file reported ${tap.tests.length} of ${tests} test results before it exited` }] };
  }
  return { file, tests: tap.tests.length, passed, failed: failures.length, timedOut: false, failures };
}

export async function runVerify(opts: { testsDir: string; againstReal: string; fileTimeoutMs: number; reportPath: string; logger: Logger }): Promise<VerifyReport> {
  const planned = plan(opts.testsDir, opts.againstReal);
  const testsReal = realpathSync(opts.testsDir);
  const files: VerifyFile[] = [];
  for (const p of planned) {
    const run = await runFile(join(testsReal, p.name), testsReal, opts.againstReal, opts.fileTimeoutMs);
    const vf = toVerifyFile(p, run);
    opts.logger.info("verify_file", { file: vf.file, tests: vf.tests, passed: vf.passed, failed: vf.failed, timedOut: vf.timedOut, exitCode: run.code, durationMs: run.durationMs });
    files.push(vf);
  }
  const report: VerifyReport = { target: relativeToProject(opts.againstReal), files };
  mkdirSync(dirname(opts.reportPath), { recursive: true });
  writeFileSync(opts.reportPath, writeJsonText(report));
  return report;
}

export function verifyTotals(r: VerifyReport): { tests: number; passed: number; failed: number } {
  return r.files.reduce((acc, f) => ({ tests: acc.tests + f.tests, passed: acc.passed + f.passed, failed: acc.failed + f.failed }), { tests: 0, passed: 0, failed: 0 });
}

/** The human summary: one totals line, then each failure and each killed file. */
export function formatVerify(r: VerifyReport, fileTimeoutMs: number): string[] {
  const n = (x: number): string => x.toLocaleString("en-US");
  const totals = verifyTotals(r);
  const lines = [`verify: ${n(totals.tests)} tests, ${n(totals.passed)} passed, ${n(totals.failed)} failed  (target: ${r.target})`];
  for (const f of r.files) {
    for (const failure of f.failures) lines.push(`  FAIL ${failure.name}`, `       ${failure.message}`);
    if (f.timedOut) lines.push(`  TIMEOUT ${f.file} (killed after ${(fileTimeoutMs / 1000).toFixed(1)} s)`);
  }
  return lines;
}
